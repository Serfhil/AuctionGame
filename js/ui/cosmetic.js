/**
 * Случайность для оформления (паузы между ставками, конфетти).
 * Намеренно отделена от util/random.js: игровой генератор можно «посеять» для воспроизводимых партий,
 * а косметика не должна сбивать его последовательность.
 */
export const randomIn = (min, max) => min + Math.random() * (max - min);
